CREATE TABLE RESERVA (
RE_USUARIO                   VARCHAR(15)NOT NULL,
RE_ID		             INT(10) NOT NULL ,
RE_FECHA        	     VARCHAR(10) NOT NULL,
RE_DIAS                  INT(10) NOT NULL,
RE_PERSONAS	             INT(3) NOT NULL,
RE_TIPO_SITIO            INT(10) NOT NULL,
RE_SITIO                 INT(10) NOT NULL,
RE_TIPO_ESTACIONAMIENTO  INT(10) NOT NULL ,
RE_ESTACIONAMIENTO       INT(10) NOT NULL,
RE_PAGO                  INT(1) NOT NULL,
RE_TOTAL			     INT(10) ,
RE_ESTADO			     INT(1)  NOT NULL,
PRIMARY KEY(RE_ID),
FOREIGN KEY (RE_USUARIO) REFERENCES CLIENTE(USUARIO),
FOREIGN KEY (RE_TIPO_SITIO) REFERENCES TIPO_SITIO(TIPO_ID),
FOREIGN KEY (RE_SITIO) REFERENCES SITIO(SI_ID),
FOREIGN KEY (RE_TIPO_ESTACIONAMIENTO) REFERENCES TIPO_ESTACIONAMIENTO(TIPO_ID),
FOREIGN KEY (RE_ESTACIONAMIENTO) REFERENCES ESTACIONAMIENTO(ES_ID),
FOREIGN KEY (RE_PAGO) REFERENCES PAGOS(PA_ID)
);	
	
CREATE TABLE DETALLE_RESERVA_CLIENTE (
DETA_ID			              INT(100) NOT NULL ,
DETA_RE_ID			          INT(10) NOT NULL,
PRIMARY KEY(DETA_ID),
FOREIGN KEY (DETA_RE_ID) REFERENCES RESERVA(RE_ID)
);
